import type { ReactNode } from "react";

// Shared stroke icons (24×24 grid, decorative: always aria-hidden). Pair them
// with a text label or aria-label on the parent control.

interface IconProps {
  size?: number;
  strokeWidth?: number;
  className?: string;
}

interface BaseProps extends IconProps {
  children: ReactNode;
  fill?: string;
}

function Icon({ size = 16, strokeWidth = 2, fill = "none", className, children }: BaseProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={fill}
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

